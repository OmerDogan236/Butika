export type PickedVariant = { id: string; title: string; available: boolean | null };

// The phone app is a separate TypeScript project, so it is loaded by URL at run
// time, as scheduler.integration.test.ts loads the mobile restock helper.
type MobileVariants = {
  variantCaptureScript: (metadataScript: string, requestId: string) => string;
  readVariants: (value: unknown) => unknown[] | null;
  variantUrl: (url: string, id: string, offeredUrl?: string) => string;
};
const mobile = async () =>
  (await import(new URL('../../../../mobile/src/lib/saved-variant.ts', import.meta.url).href)) as MobileVariants;

const metadata = `(function(){var payload={kind:'og',url:location.href,title:'Bluz'};window.ReactNativeWebView.postMessage(JSON.stringify(payload));})(); true;`;

/**
 * Runs the phone's own capture script over the page's model, as the WebView would,
 * and returns only what readVariants accepts. Both tests take their identities from
 * here so that nothing downstream is retyped by hand.
 */
export async function pickVariants(model: unknown = reyhanModel, url = reyhanUrl): Promise<PickedVariant[]> {
  const { variantCaptureScript, readVariants } = await mobile();
  const vm = await import('node:vm');
  const page = new URL(url);
  const messages: { variants?: PickedVariant[]; variantStatus?: string }[] = [];
  vm.runInNewContext(variantCaptureScript(metadata, 'gesture-1'), {
    location: { hostname: page.hostname, pathname: page.pathname, href: url },
    URL, AbortController, setTimeout, clearTimeout,
    document: { body: { classList: { contains: () => false } }, querySelector: () => null, querySelectorAll: () => [] },
    window: { productDetailModel: model, ReactNativeWebView: { postMessage: (text: string) => messages.push(JSON.parse(text)) } },
    fetch: async () => { throw new Error('No network in this fixture'); },
  });
  const captured = messages[0];
  if (captured?.variantStatus !== 'ready' || !captured.variants) throw new Error('The picker produced no choice');
  if (!readVariants(captured.variants)) throw new Error('The picker produced a choice the app would refuse');
  return captured.variants;
}

/** The saved URL the phone builds from one picked row, using that row's own identity. */
export async function pickedUrl(row: PickedVariant, url = reyhanUrl): Promise<string> {
  const { variantUrl } = await mobile();
  return variantUrl(url, row.id);
}
